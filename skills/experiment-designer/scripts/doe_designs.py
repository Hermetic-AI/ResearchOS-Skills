"""Design-of-experiments (DOE) run sheets: full and fractional factorial.

Generates factorial experiment layouts in REAL factor units with named
columns and a seeded randomized run order, so the sheet can be archived and
regenerated exactly. Two design families:

  full    every combination of the given levels (any number of levels per
          factor; cost grows as the product of level counts)
  frac2k  two-level fractional factorial 2^(k-p): base factors form a full
          2^(k-p) design, extra factors are generated by aliasing them with
          interaction columns (e.g. generator "d=ab"). Screens many factors
          cheaply at the cost of aliasing main effects with interactions.
          With no --generators it reduces to a full 2^k factorial.
  boxbehnken
          Box-Behnken response-surface design for k>=3 factors at 3 levels:
          every pair of factors is run at its +/-1 corners with all others
          at 0, plus center points. Fits a full quadratic model (main +
          two-factor interactions + curvature) without any run where ALL
          factors sit at extreme levels simultaneously.
  ccd     central composite design: a 2^k factorial core, 2k axial (star)
          points at +/-alpha, plus center points. --alpha rotatable
          (2^(k/4), default) gives a rotatable design; --alpha face keeps
          axial points on the faces of the factorial cube (within the
          tested range). Rotatable alpha > 1 puts axial points OUTSIDE the
          -1/+1 range — check those conditions are physically feasible.
  latin   Latin square: one treatment factor with g levels blocked on TWO
          nuisance factors (rows and columns, g levels each); each treatment
          appears exactly once per row and column. The treatment-to-symbol
          mapping is shuffled with the seed.
          Assumes no interactions among the three factors.

Dependencies: numpy (install: pip install numpy).

CLI usage:
    # factors.json: {"temp_C": [20, 60], "conc_mM": [1, 10], "pH": [6, 8]}
    python doe_designs.py --design full   --factors factors.json --seed 42 --out runs.csv
    python doe_designs.py --design frac2k --factors factors4.json \
        --generators "d=ab" --seed 42 --out runs.json

    # Response surface (3+ factors; levels give low/high, mid is their mean
    # unless a 3rd level is supplied):
    python doe_designs.py --design boxbehnken --factors factors3.json --seed 42
    python doe_designs.py --design ccd --factors factors3.json --alpha face --seed 42

    # Latin square (exactly ONE factor with g levels; two blocking factors):
    python doe_designs.py --design latin --factors-json '{"dose_mg": [0, 10, 50]}' \
        --row-name subject --col-name period --seed 42

    # Factors may also be given inline:
    python doe_designs.py --design full --factors-json '{"temp": [20, 40, 60], "cat": ["A", "B"]}'

    # Options: --format csv|json (default csv), --out FILE (default stdout),
    #          --no-randomize (keep standard order), --seed INT (default 0),
    #          --center-points N (boxbehnken/ccd; default 3 / 5),
    #          --alpha rotatable|face|FLOAT (ccd only)

Output: CSV or JSON table with columns run_order (unless --no-randomize),
one column per factor in real units. JSON output embeds a meta block with
the design, generators, alias structure, model-rank/efficiency diagnostics,
estimable terms, warnings, and seed.
"""

from __future__ import annotations

import argparse
import csv
import io
import itertools
import json
import math
import os
import sys

import numpy as np


def load_factors(args):
    """Factors spec: ordered mapping name -> list of levels."""
    try:
        if args.factors_json:
            spec = json.loads(args.factors_json)
        else:
            with open(args.factors, encoding="utf-8") as f:
                spec = json.load(f)
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise SystemExit(f"cannot read factors JSON: {exc}") from exc
    if not isinstance(spec, dict) or not spec:
        raise SystemExit("factors spec must be a non-empty JSON object")
    for name, levels in spec.items():
        if not isinstance(levels, list) or len(levels) < 2:
            raise SystemExit(f"factor '{name}' needs at least 2 levels")
    return spec


def full_factorial(factors):
    """Every combination of the listed levels (product of level counts)."""
    names = list(factors)
    rows = [dict(zip(names, combo))
            for combo in itertools.product(*(factors[n] for n in names))]
    return rows, {}


def frac2k(factors, generators):
    """Two-level (fractional) factorial via defining generators.

    Each generator 'd=ab' creates factor d as the elementwise product of
    coded (+1/-1) columns a*b. The first (k - #generators) factors are the
    base full factorial; generated factors are aliased with the interaction
    of their base factors.
    """
    names = list(factors)
    for n in names:
        if len(factors[n]) != 2:
            raise SystemExit(f"frac2k requires exactly 2 levels per factor; "
                             f"'{n}' has {len(factors[n])}")
    gens = []
    for g in generators or []:
        lhs, _, rhs = g.partition("=")
        lhs, rhs = lhs.strip(), rhs.strip().replace("*", "")
        if not lhs or not rhs:
            raise SystemExit(f"bad generator '{g}', expected form 'd=ab'")
        gens.append((lhs, rhs))

    k, p = len(names), len(gens)
    base_names = names[: k - p]
    gen_names = [g[0] for g in gens]
    if sorted(gen_names) != sorted(names[k - p:]):
        raise SystemExit(f"generator left-hand sides {gen_names} must match the "
                         f"last {p} factor(s) {names[k - p:]}")
    for _, rhs in gens:
        if any(letter_to_name(base_names, c) not in base_names for c in rhs):
            raise SystemExit(f"generator '{rhs}' references non-base factors; "
                             f"base factors are {base_names}")

    # coded base design: full 2^(k-p) in +/-1, sign flips fastest on first factor
    n_runs = 2 ** (k - p)
    coded = {}
    for j, nme in enumerate(base_names):
        period = 2 ** (j + 1)
        col = np.tile(np.repeat([-1.0, 1.0], period // 2), n_runs // period)
        coded[nme] = col
    aliases = {}
    for lhs, rhs in gens:
        col = np.ones(n_runs)
        for c in rhs:
            col = col * coded[letter_to_name(base_names, c)]
        coded[lhs] = col
        aliases[lhs] = f"{lhs} = {rhs} (main effect aliased with this interaction)"

    rows = []
    for i in range(n_runs):
        row = {}
        for nme in names:
            lo, hi = factors[nme][0], factors[nme][1]
            # map coded -1 -> first level, +1 -> second level
            row[nme] = lo if coded[nme][i] < 0 else hi
        rows.append(row)
    return rows, aliases


def letter_to_name(base_names, letter):
    """Generator letters a,b,c... refer to base factors in order."""
    idx = ord(letter.lower()) - ord("a")
    if 0 <= idx < len(base_names):
        return base_names[idx]
    return None


def _coded_to_real(factors):
    """Return {name: (fn mapping coded value -> real level)}.

    Coded -1/+1 map to the first/last listed level; 0 maps to the third
    level if given, else the midpoint (numeric) of the extremes.
    """
    mappers = {}
    for name, levels in factors.items():
        lo, hi = levels[0], levels[-1]
        if len(levels) >= 3:
            mid = levels[1]
        elif isinstance(lo, (int, float)) and isinstance(hi, (int, float)):
            mid = (lo + hi) / 2
        else:
            raise SystemExit(
                f"factor '{name}' needs 3 levels (low/mid/high) for a "
                f"response-surface design — non-numeric levels have no midpoint")
        if not isinstance(lo, (int, float)):
            def fn(v, lo=lo, mid=mid, hi=hi):
                return lo if v < -0.5 else (hi if v > 0.5 else mid)
        elif len(levels) >= 3:
            # piecewise linear through (-1,lo),(0,mid),(+1,hi) so a
            # user-supplied middle level is honored at the center point
            def fn(v, lo=lo, mid=mid, hi=hi):
                x = mid + v * (mid - lo) if v < 0 else mid + v * (hi - mid)
                return round(x, 10)
        else:
            half = (hi - lo) / 2
            center = (lo + hi) / 2

            def fn(v, center=center, half=half):
                x = center + v * half
                return round(x, 10)
        mappers[name] = fn
    return mappers


def box_behnken(factors, center_points):
    """Box-Behnken: each factor pair at its 4 corners, others at center."""
    names = list(factors)
    if len(names) < 3:
        raise SystemExit("boxbehnken needs at least 3 factors")
    rows = []
    for i, j in itertools.combinations(range(len(names)), 2):
        for si in (-1, 1):
            for sj in (-1, 1):
                coded = {n: 0 for n in names}
                coded[names[i]], coded[names[j]] = si, sj
                rows.append(coded)
    rows += [{n: 0 for n in names} for _ in range(center_points)]
    mappers = _coded_to_real(factors)
    return [{n: mappers[n](c[n]) for n in names} for c in rows]


def central_composite(factors, alpha, center_points):
    """CCD: 2^k factorial core + 2k axial points at +/-alpha + centers."""
    names = list(factors)
    if len(names) < 2:
        raise SystemExit("ccd needs at least 2 factors")
    k = len(names)
    if alpha == "rotatable":
        alpha = 2 ** (k / 4)
    elif alpha == "face":
        alpha = 1.0
    else:
        alpha = float(alpha)
    rows = []
    for combo in itertools.product((-1, 1), repeat=k):
        rows.append(dict(zip(names, combo)))
    for j, nme in enumerate(names):
        for s in (-1, 1):
            coded = {n: 0.0 for n in names}
            coded[nme] = s * alpha
            rows.append(coded)
    rows += [{n: 0.0 for n in names} for _ in range(center_points)]
    mappers = _coded_to_real(factors)
    return [{n: mappers[n](c[n]) for n in names} for c in rows], alpha


def latin_square(factors, row_name, col_name, seed):
    """Cyclic Latin square with a seeded shuffled treatment-symbol mapping.

    Exactly one factor with g levels is the treatment; rows and columns are
    the two blocking factors (g levels each). Assumes no interactions.
    """
    names = list(factors)
    if len(names) != 1:
        raise SystemExit("latin needs exactly ONE treatment factor; the two "
                         "blocking factors are rows and columns")
    tname = names[0]
    levels = factors[tname]
    g = len(levels)
    if g < 2:
        raise SystemExit("latin needs a treatment factor with >= 2 levels")
    rng = np.random.default_rng(seed)
    row_perm = rng.permutation(g)
    col_perm = rng.permutation(g)
    sym_perm = rng.permutation(g)  # symbol index -> treatment level index
    rows = []
    for r in row_perm:
        for c in col_perm:
            sym = (int(r) + int(c)) % g  # cyclic square in standard order
            rows.append({row_name: int(r) + 1, col_name: int(c) + 1,
                         tname: levels[int(sym_perm[sym])]})
    rows.sort(key=lambda x: (x[row_name], x[col_name]))
    return rows


def randomize(rows, seed):
    rng = np.random.default_rng(seed)
    order = (rng.permutation(len(rows)) + 1).tolist()
    out = []
    for i, row in zip(order, rows):
        out.append({"run_order": i, **row})
    out.sort(key=lambda r: r["run_order"])
    return out


def _coded_columns(rows, factors):
    columns = {}
    for name, levels in factors.items():
        ordered = list(dict.fromkeys(levels))
        mapping = {str(value): -1 + 2 * index / (len(ordered) - 1)
                   for index, value in enumerate(ordered)}
        values = [row[name] for row in rows]
        if all(isinstance(value, (int, float)) for value in values):
            low, high = min(values), max(values)
            columns[name] = np.array([
                0.0 if high == low else -1 + 2 * (value - low) / (high - low)
                for value in values
            ])
        else:
            columns[name] = np.array([mapping[str(value)] for value in values])
    return columns


def design_diagnostics(rows, factors, design):
    """Rank, conditioning, D-efficiency index, and coefficient estimability."""
    names = list(factors)
    coded = _coded_columns(rows, factors)
    terms = ["intercept"]
    columns = [np.ones(len(rows))]
    for name in names:
        terms.append(f"linear({name})")
        columns.append(coded[name])
    for left, right in itertools.combinations(names, 2):
        terms.append(f"{left}:{right}")
        columns.append(coded[left] * coded[right])
    if design in ("boxbehnken", "ccd"):
        for name in names:
            terms.append(f"quadratic({name})")
            columns.append(coded[name] ** 2)
        model = "full quadratic in coded factor coordinates"
    else:
        model = "intercept + linear factor contrasts + two-factor products"
    matrix = np.column_stack(columns)
    rank = int(np.linalg.matrix_rank(matrix))
    projection = np.linalg.pinv(matrix) @ matrix
    estimable, non_estimable = [], []
    for index, term in enumerate(terms):
        unit = np.zeros(len(terms))
        unit[index] = 1
        target = estimable if np.linalg.norm(unit - unit @ projection) < 1e-8 else non_estimable
        target.append(term)
    condition = float(np.linalg.cond(matrix)) if rank == len(terms) else None
    sign, logdet = np.linalg.slogdet(matrix.T @ matrix)
    efficiency = (0.0 if sign <= 0 or rank < len(terms)
                  else 100 * math.exp(logdet / len(terms)) / len(rows))
    warnings = []
    if any(any(not isinstance(level, (int, float)) for level in levels) or len(levels) > 2
           for levels in factors.values()):
        warnings.append("Diagnostics use one ordered linear contrast per factor; they do not represent every degree of freedom of multi-level/categorical factors.")
    if rank < len(terms):
        warnings.append("Requested screening/quadratic model is rank deficient; inspect non-estimable terms and aliases.")
    return {
        "model": model,
        "n_parameters": len(terms),
        "rank": rank,
        "residual_df": max(0, len(rows) - rank),
        "condition_number": round(condition, 6) if condition is not None and math.isfinite(condition) else None,
        "d_efficiency_percent": round(efficiency, 6),
        "estimable_terms": estimable,
        "non_estimable_terms": non_estimable,
        "warnings": warnings,
    }


def factorial_alias_structure(rows, factors):
    """Complete alias groups and defining-relation resolution for 2-level designs."""
    names = list(factors)
    if any(len(levels) != 2 for levels in factors.values()):
        return None
    coded = _coded_columns(rows, factors)
    groups = {}
    for size in range(0, len(names) + 1):
        for subset in itertools.combinations(names, size):
            column = np.ones(len(rows))
            for name in subset:
                column *= coded[name]
            sign = 1
            if tuple(column.tolist()) > tuple((-column).tolist()):
                column, sign = -column, -1
            signature = tuple(round(float(value), 8) for value in column)
            label = "I" if not subset else ":".join(subset)
            groups.setdefault(signature, []).append((label, sign, len(subset)))
    alias_groups = []
    resolution = None
    for members in groups.values():
        if len(members) > 1:
            alias_groups.append([("-" if sign < 0 else "") + label
                                 for label, sign, _ in members])
        if any(label == "I" for label, _, _ in members):
            words = [order for label, _, order in members if label != "I"]
            if words:
                resolution = min(words)
    return {"resolution": resolution, "groups": alias_groups}


def emit(rows, fmt, out, meta):
    if fmt == "json":
        text = json.dumps({"meta": meta, "runs": rows}, indent=2,
                          ensure_ascii=False, default=str)
    else:
        cols = list(rows[0].keys())
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\n")
        w.writerow(cols)
        for r in rows:
            w.writerow([r[c] for c in cols])
        text = buf.getvalue().rstrip("\n")
    if out:
        with open(out, "w", encoding="utf-8") as f:
            f.write(text + "\n")
        print(f"wrote {out}", file=sys.stderr)
    else:
        print(text)
    if fmt == "csv":
        print(json.dumps(meta, ensure_ascii=False), file=sys.stderr)


def main(argv=None):
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--version", action="version", version="%(prog)s 0.1.0")
    p.add_argument("--design", choices=["full", "frac2k", "boxbehnken", "ccd", "latin"],
                   required=True)
    p.add_argument("--factors", help="path to factors JSON file")
    p.add_argument("--factors-json", help="inline factors JSON string")
    p.add_argument("--generators", nargs="*", default=None,
                   help="(frac2k) defining generators, e.g. \"d=ab\" \"e=ac\"")
    p.add_argument("--alpha", default="rotatable",
                   help="(ccd) 'rotatable' (default), 'face', or a numeric value")
    p.add_argument("--center-points", type=int, default=None,
                   help="(boxbehnken/ccd) center replicates; default 3 / 5")
    p.add_argument("--row-name", default="row", help="(latin) row block name")
    p.add_argument("--col-name", default="col", help="(latin) column block name")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--no-randomize", action="store_true",
                   help="keep standard (unrandomized) run order")
    p.add_argument("--format", choices=["csv", "json"], default="csv")
    p.add_argument("--out", default=None, help="output file (default stdout)")
    p.add_argument("--force", action="store_true", help="replace an existing --out file")
    args = p.parse_args(argv)
    if args.out and args.factors and os.path.abspath(args.out) == os.path.abspath(args.factors):
        raise SystemExit("output must not replace the --factors input file")
    if args.out and os.path.exists(args.out) and not args.force:
        raise SystemExit(f"output exists: {args.out}; use --force to replace it")

    if not args.factors and not args.factors_json:
        raise SystemExit("provide --factors FILE or --factors-json JSON")
    factors = load_factors(args)

    aliases, alpha_used = {}, None
    if args.design == "full":
        rows = full_factorial(factors)[0]
    elif args.design == "frac2k":
        rows, aliases = frac2k(factors, args.generators)
    elif args.design == "boxbehnken":
        rows = box_behnken(factors, args.center_points or 3)
    elif args.design == "ccd":
        rows, alpha_used = central_composite(
            factors, args.alpha, args.center_points or 5)
    else:
        rows = latin_square(factors, args.row_name, args.col_name, args.seed)

    if not args.no_randomize and args.design != "latin":
        rows = randomize(rows, args.seed)

    meta = {"design": args.design, "n_runs": len(rows),
            "factors": {k: v for k, v in factors.items()},
            "generators": args.generators or [], "aliases": aliases,
            "randomized": True if args.design == "latin" else not args.no_randomize,
            "seed": args.seed}
    diagnostic_rows = [{key: value for key, value in row.items()
                        if key != "run_order"} for row in rows]
    if args.design != "latin":
        meta["design_diagnostics"] = design_diagnostics(
            diagnostic_rows, factors, args.design)
    if args.design in ("full", "frac2k"):
        meta["alias_structure"] = factorial_alias_structure(
            diagnostic_rows, factors)
    if args.design == "ccd":
        meta["alpha"] = alpha_used
        if alpha_used > 1:
            meta["warning"] = ("rotatable alpha > 1: axial points lie OUTSIDE "
                               "the -1/+1 factor range; verify those conditions "
                               "are physically feasible and safe")
    if args.design == "latin":
        meta["row_block"] = args.row_name
        meta["col_block"] = args.col_name
        meta["warning"] = ("Latin square assumes NO interactions among treatment, "
                           "row, and column factors; treatment-to-symbol mapping "
                           "is shuffled with the seed")
    if aliases:
        meta["warning"] = ("fractional design: generated factors are aliased "
                           "with interactions (see 'aliases'); a significant "
                           "main effect may be an aliased interaction")
    emit(rows, args.format, args.out, meta)


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):  # Windows consoles: force UTF-8
        sys.stdout.reconfigure(encoding="utf-8")
    main()
